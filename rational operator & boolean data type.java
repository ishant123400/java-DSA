//{> , < , >= , <= , != , ==} [!= meaning is not equal to]
class operator{
    public static void main (String[] args){
        System.out.println(5>6);
        System.out.println(8<7);
        System.out.println(7>=7);
        System.out.println(8<=7);
        System.out.println(9==9);
        System.out.println(7*5>=35);
        System.out.println(5!=5);

    }

}