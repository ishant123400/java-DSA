class basicsalgebra{
    public static void main (String[] args){
        float x=(float)1+2*2;
        System.out.println(x);
        float y=(float)2+8*2/2*3;//priority me ham (*,/,%   >>   +,-);; aur ishme hamm left to right priority dete hai (* or / or % me );;
        System.out.println(y);

        //increment decrement symbol: {++x , --x , x++ , x--}
        int a=4;
         System.out.println(a);
         a += 6;
        System.out.println(a);
        a -=4;
        System.out.println(a);
        a *=2;
        System.out.println(a) ;
        
        //direct use {++x , --x , x++ , x--}
        int b=6;
        System.out.println(b++);//post increment iska mtlb hai pahele value use karo firr yek badha do❤️
        System.out.println(b);
        int c=4;
        System.out.println(++c);//pre increment iska mtlb pahele yek badhta hai firr value likhata hai❤️
        System.out.println(c);
        System.out.println("ishant singh");
        System.out.println(--c);//pre decrement💕
        System.out.println(c);
        System.out.println("ishant");
        System.out.println(c--);//post decrement💕
        System.out.println(c);
        // new code for learn. 😘
        int g=5;
        int h=++g;
        System.out.println(g+" "+h);
        int j=5;
        int k=j++;
        System.out.println(k+" "+j);
        // by me 😂
        int l=3;
        int m=9;
        System.out.println(l+" ishant singh "+m);



    }
    
}
